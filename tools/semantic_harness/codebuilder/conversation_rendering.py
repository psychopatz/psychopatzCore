def _en_first(value: Any) -> str | None:
    if isinstance(value, str):
        return value
    if isinstance(value, list) and value and isinstance(value[0], str):
        return value[0]
    return None


def _strip_lua_multi_locale_corpora(value: Any) -> Any:
    """Strip multi-locale prose corpora from generated Lua records, leaving keys and EN fallbacks."""
    if isinstance(value, list):
        out_list: list[Any] = []
        for item in value:
            if (
                isinstance(item, dict)
                and item.get("type") == "construction"
                and str(item.get("locale") or "").upper() not in {"", "EN"}
            ):
                continue
            out_list.append(_strip_lua_multi_locale_corpora(item))
        return out_list
    if not isinstance(value, dict):
        return value

    out: dict[str, Any] = {}
    is_construction = value.get("type") == "construction"
    is_lexeme = value.get("type") == "lexeme"
    for k, v in value.items():
        if k == "translations" and isinstance(v, dict):
            continue
        if k == "display" and isinstance(v, dict) and is_locale_map(v):
            continue
        if k == "forms" and isinstance(v, dict) and is_locale_map(v):
            en_val = _en_first(v.get("EN"))
            if en_val is not None and "fallback" not in value:
                out["fallback"] = en_val
            if is_lexeme and "id" in value and "translationKey" not in value:
                out["translationKey"] = f"convo.{value['id']}"
            continue
        if k == "locale" and is_construction:
            continue
        if k in {"text", "label", "utterance", "choice", "responseText"} and is_locale_map(v):
            en_val = _en_first(v.get("EN"))
            fb_key = (
                "fallback"
                if k == "text"
                else ("labelFallback" if k == "label" else ("utteranceFallback" if k == "utterance" else f"{k}Fallback"))
            )
            if en_val is not None and fb_key not in value and fb_key not in out:
                out[fb_key] = en_val
            continue
        out[k] = _strip_lua_multi_locale_corpora(v)

    if is_construction and "id" in out and "translationKey" not in out:
        parts = str(out["id"]).split(".")
        if len(parts) >= 3 and parts[0] == "construction" and parts[1].lower() == "en":
            out["translationKey"] = "convo.construction." + ".".join(parts[2:])
        else:
            out["translationKey"] = f"convo.{out['id']}"
    return out


def render_conversation_ui_module(
    model: dict[str, Any],
    *,
    include_owner: str | None = None,
    include_owners: tuple[str, ...] | None = None,
) -> str:
    """Render one package-owned generated Conversation UI list."""
    records = model.get("ui", [])
    owners = None
    if include_owners is not None:
        owners = {normalize_owner(owner) for owner in include_owners}
    elif include_owner is not None:
        owners = {normalize_owner(include_owner)}
    if owners is not None:
        locations = model.get("locations") or {}
        ui_locations = model.get("uiLocations") or {}
        records = [
            record
            for record in records
            if normalize_owner(
                (ui_locations.get(str(record.get("id"))) or locations.get(str(record.get("id"))) or {}).get("owner")
            ) in owners
        ]
    stripped = _strip_lua_multi_locale_corpora(records)
    return (
        "-- Generated by the manifest-backed Conversation compiler; do not edit by hand.\n"
        "return " + _lua_value(stripped, 0) + "\n"
    )

def render_conversation_lua_records(records: list[dict[str, Any]]) -> str:
    stripped = _strip_lua_multi_locale_corpora(records)
    return "-- Generated; do not edit by hand.\nreturn " + _lua_value(stripped, 0) + "\n"

def _chunk_records(
    records: list[dict[str, Any]],
    *,
    kind: str,
    module_prefix: str,
    max_bytes: int = CONVERSATION_MAX_SHARD_BYTES,
) -> tuple[list[tuple[str, str]], list[dict[str, Any]]]:
    """Render one bounded generated shard per canonical source owner.

    Numeric overflow parts are intentionally forbidden. If a canonical source
    owns too much generated runtime data, the canonical source must be split by
    semantic subdomain instead.
    """
    modules: list[tuple[str, str]] = []
    reports: list[dict[str, Any]] = []
    grouped: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for record in records:
        rec_owner = str(record.get("owner") or "")
        source_shard = str(
            record.get("moduleSourceShard")
            or record.get("sourceShard")
            or f"{kind.lower()}/{record.get('domain') or 'general'}.json"
        )
        grouped.setdefault((rec_owner, source_shard), []).append(record)

    names = ModuleNameRegistry()
    for (rec_owner, source_shard) in sorted(grouped):
        items = sorted(
            grouped[(rec_owner, source_shard)],
            key=(
                (lambda item: (item.get("order", 0), str(item.get("id", ""))))
                if kind == "UI"
                else (lambda item: str(item.get("id", "")))
            ),
        )
        if len(items) > CONVERSATION_MAX_RECORDS_PER_SHARD:
            raise CompileError(
                "canonical Conversation source exceeds the generated "
                f"{CONVERSATION_MAX_RECORDS_PER_SHARD}-definition hard budget; "
                f"split by semantic subdomain: {source_shard}"
            )
        runtime_items = _runtime_records(items)
        for runtime_item in runtime_items:
            if isinstance(runtime_item, dict):
                runtime_item.pop("moduleSourceShard", None)
        source = render_conversation_lua_records(runtime_items)
        size = len(source.encode("utf-8"))
        if size > max_bytes:
            raise CompileError(
                "canonical Conversation source renders above the "
                f"{max_bytes}-byte hard shard budget; split by semantic subdomain: "
                f"{source_shard}"
            )
        eff_prefix = (
            conversation_prefix(normalize_owner(rec_owner))
            if rec_owner
            else module_prefix
        )
        module = source_owned_module(
            f"{eff_prefix}/{kind}",
            source_shard,
            names,
        )
        modules.append((module, source))
        reports.append({
            "module": module,
            "kind": kind,
            "domain": str(
                items[0].get("conversationDomain")
                or items[0].get("domain")
                or "general"
            ),
            "sourceShard": str(items[0].get("sourceShard") or source_shard),
            "recordCount": len(items),
            "recordIDs": [
                str(item.get("id"))
                for item in items
                if isinstance(item.get("id"), str)
            ],
            "bytes": size,
        })
    return modules, reports

def _render_pack_shard_plan(
    records: list[dict[str, Any]],
    *,
    module_prefix: str,
) -> tuple[list[tuple[str, str]], list[dict[str, Any]]]:
    """Render static pack data separately from runtime callback adapters."""
    grouped: dict[str, list[dict[str, Any]]] = {}
    for record in records:
        source_shard = str(
            record.get("moduleSourceShard")
            or record.get("sourceShard")
            or "packs/general.json"
        )
        grouped.setdefault(source_shard, []).append(record)
    modules: list[tuple[str, str]] = []
    reports: list[dict[str, Any]] = []
    names = ModuleNameRegistry()
    for source_shard in sorted(grouped):
        items = sorted(grouped[source_shard], key=lambda item: str(item.get("id", "")))
        runtime_items = []
        for item in items:
            runtime_item = _copy_json(item)
            for key in ("owner", "domain", "sourceShard", "moduleSourceShard"):
                runtime_item.pop(key, None)
            runtime_items.append(runtime_item)
        source = render_conversation_lua_records(runtime_items)
        size = len(source.encode("utf-8"))
        if size > CONVERSATION_MAX_SHARD_BYTES:
            raise CompileError(
                "canonical semantic-pack source renders above the hard shard budget: "
                + source_shard
            )
        module = source_owned_module(
            f"{module_prefix}/Packs",
            source_shard,
            names,
        )
        modules.append((module, source))
        reports.append({
            "module": module,
            "kind": "Packs",
            "domain": str(items[0].get("domain") or "general"),
            "sourceShard": str(items[0].get("sourceShard") or source_shard),
            "recordCount": len(items),
            "recordIDs": [
                str(item.get("id"))
                for item in items
                if isinstance(item.get("id"), str)
            ],
            "bytes": size,
        })
    return modules, reports

