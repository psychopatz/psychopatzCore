from .validation import validate_project


def used_source_ids(project: dict[str, Any]) -> set[str]:
    sources = set()
    regions = project.get("regions") or {}
    for layer in project.get("layers") or []:
        if not isinstance(layer, dict):
            continue
        source_id = str(layer.get("source") or "")
        region_id = str(layer.get("region") or "")
        if not region_id and source_id in regions:
            region_id = source_id
        if region_id and isinstance(regions.get(region_id), dict):
            source_id = str(regions[region_id].get("source") or "")
        if source_id:
            sources.add(source_id)
    return sources


def _lua_string(value: Any) -> str:
    return '"' + str(value or "").replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _lua_rect(value: Any) -> str:
    rect = parse_rect(value)
    return "{ x = %d, y = %d, w = %d, h = %d }" % tuple(rect)


def _game_texture_path(device_path: str, filename: str) -> str:
    return "media/ui/" + "/".join(part for part in (device_path, filename) if part)


def _manifest(project: dict[str, Any], device_path: str, textures: list[dict[str, Any]]) -> str:
    device = project.get("device") or {}
    lcd = project.get("lcd") or {}
    lines = [
        "-- Generated by Psychopatz Asset Harness; source project remains authoritative.",
        "return {",
        "  schemaVersion = 1,",
        f"  id = {_lua_string(device.get('id') or project.get('project_id'))},",
        f"  family = {_lua_string(device.get('family'))},",
        f"  model = {_lua_string(device.get('model'))},",
        f"  fullType = {_lua_string(device.get('fullType'))},",
        "  artwork = {",
        f"    shell = {_lua_string(next((item['game_path'] for item in textures if item.get('kind') == 'shell'), textures[0]['game_path'] if textures else ''))},",
        "    variants = {",
    ]
    for item in textures:
        if item.get("kind") != "shell":
            lines.append(f"      [{_lua_string(item.get('name'))}] = {_lua_string(item['game_path'])},")
    lines.extend(["    },", "  },"])
    canvas = project.get("canvas") or {}
    lines.extend([
        f"  canvas = {{ w = {int(canvas.get('width', 0))}, h = {int(canvas.get('height', 0))} }},",
        "  lcd = {",
    ])
    for key in ("aperture", "backing", "content"):
        if lcd.get(key) is not None:
            lines.append(f"    {key} = {_lua_rect(lcd[key])},")
    lines.append("  },")
    lines.append("  controls = {")
    for control in project.get("controls") or []:
        if not isinstance(control, dict):
            continue
        rect = control.get("rect", control.get("hitbox"))
        if rect is None:
            continue
        lines.append(
            f"    {{ id = {_lua_string(control.get('id'))}, rect = {_lua_rect(rect)}, hitbox = {_lua_rect(control.get('hitbox', rect))}, action = {_lua_string(control.get('action'))} }},"
        )
    lines.extend(["  },", f"  preferredTheme = {_lua_string(project.get('preferred_theme', 'green'))},", "}", ""])
    return "\n".join(lines)


def _export_roots(project_path: Path, project: dict[str, Any]) -> tuple[Path, Path, str]:
    workspace = project_workspace(project_path, project)
    config = project.get("export") or {}
    runtime_root = resolve_reference(workspace, str(config.get("runtime_root") or "runtime"))
    device_path = str(config.get("device_path") or "psychopatz/radio/devices/unknown")
    if Path(device_path).is_absolute() or ".." in Path(device_path).parts:
        raise AssetHarnessError("EXPORT_PATH_UNSAFE", "export device_path may not escape the runtime root")
    device_dir = ensure_within(runtime_root, runtime_root / device_path)
    return workspace, device_dir, device_path.replace("\\", "/").strip("/")


def build_export_plan(project_path: Path, project: dict[str, Any]) -> dict[str, Any]:
    validation = validate_project(project_path, project)
    if not validation["ok"]:
        raise AssetHarnessError(
            "VALIDATION_FAILED",
            "export requires a project with no validation errors",
            diagnostics=validation["diagnostics"],
        )
    workspace, device_dir, device_path = _export_roots(project_path, project)
    config = project.get("export") or {}
    entries = config.get("textures") or [{"name": "shell_front", "filename": "shell_front.png", "variant": "pristine", "kind": "shell"}]
    files: list[dict[str, Any]] = []
    rendered: list[dict[str, Any]] = []
    for entry in entries:
        if not isinstance(entry, dict):
            raise AssetHarnessError("EXPORT_INVALID", "export texture entries must be objects")
        filename = str(entry.get("filename") or "")
        if not filename or Path(filename).name != filename or Path(filename).suffix.lower() != ".png":
            raise AssetHarnessError("EXPORT_INVALID", f"invalid export filename: {filename}")
        variant = str(entry.get("variant", "pristine"))
        image, metadata = render_image(project_path, project, variant=variant, state=entry.get("state"), scale=1, content_color=None)
        content = png_bytes(image)
        target = ensure_within(device_dir, device_dir / filename)
        descriptor = {
            "kind": str(entry.get("kind", "texture")),
            "name": str(entry.get("name") or Path(filename).stem),
            "variant": variant,
            "path": str(target),
            "game_path": _game_texture_path(device_path, filename),
            "bytes": len(content),
            "sha256": sha256_bytes(content),
            "exists": target.exists(),
            "would_overwrite": target.exists(),
            "width": metadata["output_width"],
            "height": metadata["output_height"],
            "_content": content,
        }
        files.append(descriptor)
        rendered.append(descriptor)
    manifest_filename = str(config.get("manifest_filename") or "skin.lua")
    if Path(manifest_filename).name != manifest_filename or not manifest_filename.endswith(".lua"):
        raise AssetHarnessError("EXPORT_INVALID", f"invalid manifest filename: {manifest_filename}")
    manifest_path = ensure_within(device_dir, device_dir / manifest_filename)
    manifest_entries = [dict(item) for item in rendered]
    manifest_text = _manifest(project, device_path, manifest_entries)
    manifest_bytes = manifest_text.encode("utf-8")
    files.append({
        "kind": "lua_manifest",
        "name": manifest_filename,
        "path": str(manifest_path),
        "game_path": _game_texture_path(device_path, manifest_filename),
        "bytes": len(manifest_bytes),
        "sha256": sha256_bytes(manifest_bytes),
        "exists": manifest_path.exists(),
        "would_overwrite": manifest_path.exists(),
        "_content": manifest_bytes,
    })
    return {
        "files": files,
        "runtime_root": str(device_dir.parent),
        "device_dir": str(device_dir),
        "device_path": device_path,
        "manifest": manifest_text,
        "approval_required": sorted(source_id for source_id in used_source_ids(project) if not bool((project.get("sources") or {}).get(source_id, {}).get("approved"))),
        "validation": validation["summary"],
    }


def public_plan(plan: dict[str, Any]) -> dict[str, Any]:
    result = {key: value for key, value in plan.items() if key != "manifest"}
    result["files"] = [{key: value for key, value in item.items() if not key.startswith("_")} for item in plan["files"]]
    result["manifest_sha256"] = sha256_bytes(plan["manifest"].encode("utf-8"))
    return result


def apply_export(project_path: Path, project: dict[str, Any], *, approved: bool) -> dict[str, Any]:
    if not approved:
        raise AssetHarnessError("EXPORT_APPROVAL_REQUIRED", "export apply requires the explicit --approved flag")
    unapproved = sorted(source_id for source_id in used_source_ids(project) if not bool((project.get("sources") or {}).get(source_id, {}).get("approved")))
    if unapproved:
        raise AssetHarnessError(
            "SOURCE_NOT_APPROVED",
            "runtime export requires approved sources",
            diagnostics=[diagnostic("SOURCE_NOT_APPROVED", f"source is not approved: {source_id}", asset=source_id) for source_id in unapproved],
        )
    plan = build_export_plan(project_path, project)
    conflicts = [item for item in plan["files"] if item["exists"]]
    if conflicts:
        diagnostics = [diagnostic(
            "EXPORT_CONFLICT",
            "export refuses to overwrite an existing runtime file",
            path=item["path"],
            remediation="review the staged plan and remove the conflict explicitly before applying",
        ) for item in conflicts]
        raise AssetHarnessError("EXPORT_CONFLICT", "runtime export has existing files", diagnostics=diagnostics)
    temp_paths: list[tuple[Path, Path]] = []
    try:
        for item in plan["files"]:
            target = Path(item["path"])
            target.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=target.parent, prefix=f".{target.name}.", suffix=".tmp", delete=False) as handle:
                temporary = Path(handle.name)
                handle.write(item["_content"])
                handle.flush()
                os.fsync(handle.fileno())
            temp_paths.append((temporary, target))
        for temporary, target in temp_paths:
            os.replace(temporary, target)
    finally:
        for temporary, _ in temp_paths:
            temporary.unlink(missing_ok=True)
    output_hashes = {item["path"]: item["sha256"] for item in plan["files"]}
    project.setdefault("export", {})["output_hashes"] = output_hashes
    project["export"]["last_applied_revision"] = sha256_bytes("\n".join(f"{key}:{value}" for key, value in sorted(output_hashes.items())).encode("utf-8"))
    save_project(project_path, project)
    return plan


def verify_export(project_path: Path, project: dict[str, Any]) -> dict[str, Any]:
    expected = (project.get("export") or {}).get("output_hashes") or {}
    if not expected:
        raise AssetHarnessError("EXPORT_NOT_APPLIED", "project has no recorded export hashes")
    diagnostics: list[dict[str, Any]] = []
    checked = 0
    workspace = project_workspace(project_path, project)
    for path_text, expected_hash in sorted(expected.items()):
        path = Path(path_text).expanduser().resolve()
        checked += 1
        try:
            ensure_within(workspace, path)
        except AssetHarnessError:
            diagnostics.append(diagnostic("EXPORT_PATH_UNSAFE", "recorded export path escapes the project workspace", path=str(path)))
            continue
        if not path.exists():
            diagnostics.append(diagnostic("EXPORTED_FILE_MISSING", "exported file is missing", path=str(path)))
            continue
        actual = sha256_path(path)
        if actual != expected_hash:
            diagnostics.append(diagnostic("EXPORTED_HASH_MISMATCH", "exported file hash differs", path=str(path)))
        if path.suffix.lower() == ".png":
            try:
                with Image.open(path) as image:
                    image.verify()
            except Exception as error:
                diagnostics.append(diagnostic("EXPORTED_PNG_INVALID", f"exported PNG cannot be reopened: {error}", path=str(path)))
        elif path.suffix.lower() == ".lua":
            try:
                manifest = path.read_text(encoding="utf-8")
                if "media/ui/" not in manifest:
                    diagnostics.append(diagnostic("MANIFEST_PATH_INVALID", "skin manifest has no game-relative media/ui path", path=str(path)))
                for png_path in expected:
                    if png_path.lower().endswith(".png") and Path(png_path).name not in manifest:
                        diagnostics.append(diagnostic("MANIFEST_TEXTURE_MISSING", "skin manifest does not reference an exported texture", path=str(path), asset=Path(png_path).name))
            except (OSError, UnicodeError) as error:
                diagnostics.append(diagnostic("MANIFEST_UNREADABLE", f"skin manifest cannot be read: {error}", path=str(path)))
    return {"ok": not diagnostics, "summary": {"checked": checked, "failed": len(diagnostics)}, "diagnostics": diagnostics}
